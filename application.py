plt.show()

data["RiskScore"] = (
    data["HighValueTxn"] * 3 +
    data["HighLoginAttempts"] * 2 +
    data["RapidTxn"] * 2 +
    data["TxnToBalanceRatio"]
)

data[["AccountID", "TransactionAmount", "RiskScore"]].head()

plt.figure()
plt.hist(data["RiskScore"], bins=30)
plt.title("Risk Score Distribution")
plt.show()

data["RiskLevel"] = pd.cut(
    data["RiskScore"],
    bins=[-1, 2, 5, np.inf],
    labels=["Low", "Medium", "High"]
)

data["RiskLevel"].value_counts()

features = [
    "TransactionAmount",
    "TransactionDuration",
    "LoginAttempts",
    "AccountBalance",
    "TimeGap",
    "TxnToBalanceRatio"
]

X = data[features]

from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import IsolationForest
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

iso_forest = IsolationForest(
    n_estimators=100,
    contamination=0.05,
    random_state=42
)

data["IF_Anomaly"] = iso_forest.fit_predict(X_scaled)

data["IF_Anomaly"] = data["IF_Anomaly"].map({1: 0, -1: 1})
data["IF_Anomaly"].value_counts()

plt.figure()
plt.scatter(
    data["TransactionAmount"],
    data["AccountBalance"],
    c=data["IF_Anomaly"]
)
plt.xlabel("Transaction Amount")
plt.ylabel("Account Balance")
plt.title("Isolation Forest Anomaly Detection")
plt.show()

import tensorflow as tf
from tensorflow.keras.models import Model
from tensorflow.keras.layers import Input, Dense

input_dim = X_scaled.shape[1]

input_layer = Input(shape=(input_dim,))
encoded = Dense(16, activation="relu")(input_layer)
encoded = Dense(8, activation="relu")(encoded)

decoded = Dense(16, activation="relu")(encoded)
decoded = Dense(input_dim, activation="linear")(decoded)

autoencoder = Model(inputs=input_layer, outputs=decoded)
autoencoder.compile(
    optimizer="adam",
    loss="mse"
)

autoencoder.fit(
    X_scaled,
    X_scaled,
    epochs=20,
    batch_size=32,
    validation_split=0.1,
    verbose=1
)

reconstructions = autoencoder.predict(X_scaled)
reconstruction_error = np.mean(np.square(X_scaled - reconstructions), axis=1)

data["AE_Error"] = reconstruction_error

threshold = np.percentile(reconstruction_error, 95)

data["AE_Anomaly"] = np.where(
    reconstruction_error > threshold, 1, 0
)

data["AE_Anomaly"].value_counts()

plt.figure()
plt.hist(data["AE_Error"], bins=30)
plt.axvline(threshold)
plt.title("Autoencoder Reconstruction Error")
plt.show()

data["FinalRiskScore"] = (
    data["RiskScore"] +
    data["IF_Anomaly"] * 3 +
    data["AE_Anomaly"] * 3
)

data["FinalRiskLevel"] = pd.cut(
    data["FinalRiskScore"],
    bins=[-1, 4, 8, np.inf],
    labels=["Low", "Medium", "High"]
)

data["FinalRiskLevel"].value_counts()

