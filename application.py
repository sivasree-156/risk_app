import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv("bank_transactions_data_2.csv")
df.head()

cols = [
    "AccountID",
    "TransactionDate",
    "PreviousTransactionDate",
    "TransactionAmount",
    "TransactionType",
    "Channel",
    "TransactionDuration",
    "LoginAttempts",
    "AccountBalance",
    "CustomerAge"
]

data = df[cols].copy()

data["TransactionDate"] = pd.to_datetime(data["TransactionDate"])
data["PreviousTransactionDate"] = pd.to_datetime(data["PreviousTransactionDate"])

data["TimeGap"] = (
    data["TransactionDate"] - data["PreviousTransactionDate"]
).dt.total_seconds() / 3600

print("Shape:", data.shape)
print("\nMissing Values:\n", data.isnull().sum())
data.describe()

data = data[data["TransactionAmount"] > 0]

# Fill missing temporal gaps
data["TimeGap"] = data["TimeGap"].fillna(data["TimeGap"].median())

# Cap outliers (TransactionAmount)
Q1 = data["TransactionAmount"].quantile(0.25)
Q3 = data["TransactionAmount"].quantile(0.75)
IQR = Q3 - Q1

data = data[
    (data["TransactionAmount"] >= Q1 - 1.5*IQR) &
    (data["TransactionAmount"] <= Q3 + 1.5*IQR)
]

data["HighValueTxn"] = np.where(
    data["TransactionAmount"] > data["TransactionAmount"].quantile(0.90), 1, 0
)

# Frequent login flag
data["HighLoginAttempts"] = np.where(data["LoginAttempts"] > 3, 1, 0)

# Short time gap flag
data["RapidTxn"] = np.where(data["TimeGap"] < 1, 1, 0)

# Balance ratio
data["TxnToBalanceRatio"] = data["TransactionAmount"] / data["AccountBalance"]

num_cols = [
    "TransactionAmount",
    "TransactionDuration",
    "LoginAttempts",
    "TimeGap",
    "TxnToBalanceRatio"
]

for col in num_cols:
    plt.figure()
    plt.hist(data[col], bins=30)
    plt.title(f"{col} Distribution")
    plt.show()

plt.figure()
plt.boxplot(data["TransactionAmount"])
